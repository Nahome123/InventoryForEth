/** Translate one piece of UI text, or return null to leave it as is. */
export function translateAm(text: string): string | null {
  const t = text.replace(/\s+/g, " ").trim();
  if (!t || !/[A-Za-z]/.test(t)) return null;
  const hit = AM[t];
  if (hit !== undefined) return hit;
  for (const [re, fn] of AM_PATTERNS) {
    const m = t.match(re);
    if (m) return fn(m);
  }
  return null;
}
